#!/usr/bin/env python3
"""24.11.2026: число каналов 60 -> 61 (добавлен ТВ-3) со склонением: «61 канал», «всех 61 канала», «61 канал доступен».
Запускать последним (после gen_remove_rtr_euro.py, который выравнивает число до 60). Идемпотентен: «60 минут» и другие числа не трогает."""
import sys, os, re, glob
ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else '.')
RU = [
    ('60 каналов доступны', '61 канал доступен'), ('60 каналов работают', '61 канал работает'),
    ('всех 60 каналов', 'всех 61 канала'), ('просмотру 60 российских каналов', 'просмотру 61 российского канала'),
    ('просмотра 60 каналов', 'просмотра 61 канала'), ('трансляций 60 российских телеканалов', 'трансляций 61 российского телеканала'),
    ('к 60 русским телеканалам', 'к 61 русскому телеканалу'), ('представлены 60 каналов', 'представлен 61 канал'),
    ('Собрано 60 каналов', 'Собран 61 канал'), ('собрано 60 российских каналов', 'собран 61 российский канал'),
    ('потоки 60 телеканалов', 'потоки 61 телеканала'),
    ('60 русских каналов', '61 русский канал'), ('60 российских каналов', '61 российский канал'),
    ('60 российских телеканалов', '61 российский телеканал'), ('60 русскоязычных телеканалов', '61 русскоязычный телеканал'),
    ('60 русским телеканалам', '61 русскому телеканалу'), ('60 каналов', '61 канал'), ('60 телеканалов', '61 телеканал'),
]
EN = re.compile(r'(?<![\d.,%#:\-])\b60 (?=(?:channels|Channels|Russian|live|Live|TV)\b)')
def items(s):
    def blk(m):
        b = m.group(0); n = len(re.findall(r'"@type":\s*"ListItem"', b))
        return re.sub(r'"numberOfItems":\s*\d+', '"numberOfItems": %d' % n, b) if n >= 55 else b
    return re.sub(r'"@type":\s*"ItemList".*?\]\s*\}', blk, s, flags=re.S)
n = 0
for f in glob.glob(os.path.join(ROOT, '**/*'), recursive=True):
    if not f.endswith(('.html', '.xml', '.json', '.txt', '.md')) or '/tools/' in f or '/.git/' in f or '/node_modules/' in f: continue
    try: s = o = open(f, encoding='utf-8').read()
    except Exception: continue
    for a, b in RU: s = re.sub(r'(?<![\d.,])' + re.escape(a), b, s)
    s = EN.sub('61 ', s)
    if os.path.relpath(f, ROOT) in ('index.html', 'en/index.html'): s = items(s)
    if s != o: open(f, 'w', encoding='utf-8').write(s); n += 1
print('gen_count61: файлов изменено', n)
